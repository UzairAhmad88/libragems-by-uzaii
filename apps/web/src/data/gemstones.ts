export function getGemstoneBySlug(slug: string): GemstoneProduct | undefined {
  return GEMSTONE_PRODUCTS.find((g) => g.slug === slug);
}

export function getAllGemstones(): GemstoneProduct[] {
  return GEMSTONE_PRODUCTS;
}

export function getGemstonesByCategory(category: string): GemstoneProduct[] {
  if (!category || category === "all") return GEMSTONE_PRODUCTS;
  return GEMSTONE_PRODUCTS.filter((g) => g.category === category);
}
